"""Generate the Explorer HTTP surface from pinned OpenAPI contracts.

Outputs (all reproducible, checked in CI with --check):
  * APGI-Explorer/Core/APIOperationCatalog+Generated.swift  - every operation of
    contracts/openapi-v1.json (methods, routes, parameters, body requirement,
    authentication, successful status codes). Requests/responses are lossless
    JSON values; this is a transport catalog, not a typed schema SDK.
  * APGI-Explorer/Core/ResearchOperationCatalog+Generated.swift - the Explorer
    research operations from contracts/explorer-research-v1.json, an extract of
    the apgi-api OpenAPI that is NOT yet deployed. Research stays disabled.
  * APGI-Explorer/Services/APGIAPIClient+Generated.swift - public meta/version.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
METHODS = ('get', 'post', 'put', 'patch', 'delete')
LOCATIONS = {'path', 'query', 'header', 'cookie'}


def load(name):
    path = ROOT / 'contracts' / name
    return path, json.loads(path.read_text())


def operations(spec):
    """Return normalised operation dicts in a stable order (path, then method)."""
    assert spec['openapi'].startswith('3.')
    result = []
    for path in sorted(spec['paths']):
        item = spec['paths'][path]
        assert not item.get('parameters'), f'path-level parameters unsupported: {path}'
        for method in METHODS:
            if method not in item:
                continue
            op = item[method]
            params = []
            for p in op.get('parameters', []):
                assert p['in'] in LOCATIONS, p
                params.append((p['name'], p['in'], bool(p.get('required', False))))
            body = op.get('requestBody')
            if body is None:
                requirement = 'none'
            else:
                assert set(body['content']) == {'application/json'}, op['operationId']
                requirement = 'required' if body.get('required') else 'optional'
            security = op.get('security')
            assert security in (None, [{'HTTPBearer': []}]), f'unknown scheme {security}'
            ok = sorted(int(c) for c in op['responses'] if c.startswith('2'))
            assert ok, op['operationId']
            result.append(dict(id=op['operationId'], method=method.upper(), path=path,
                               params=params, body=requirement,
                               auth=security is not None, ok=ok))
    ids = [o['id'] for o in result]
    assert len(ids) == len(set(ids)), 'operationIds must be unique'
    return result


def swift_string(text):
    return json.dumps(text)


def catalog_source(spec_path, spec, enum_name, doc):
    ops = operations(spec)
    lines = [
        '// Generated by scripts/generate_api_client.py. Do not edit.',
        '// Source: contracts/' + spec_path.name,
        '// OpenAPI SHA-256: ' + hashlib.sha256(spec_path.read_bytes()).hexdigest(),
        'import Foundation', '', f'/// {doc}', f'nonisolated enum {enum_name} {{',
        f'  static let operationCount = {len(ops)}', '', '  static let all: [APIOperation] = [']
    for o in ops:
        params = ', '.join(
            f'APIParameter(name: {swift_string(n)}, location: .{loc}, required: {str(req).lower()})'
            for n, loc, req in o['params'])
        lines.append(
            f'    APIOperation(id: {swift_string(o["id"])}, method: .{o["method"].lower()}, '
            f'path: {swift_string(o["path"])}, parameters: [{params}], body: .{o["body"]}, '
            f'requiresAuthentication: {str(o["auth"]).lower()}, '
            f'successStatuses: {o["ok"]}),')
    lines += ['  ]', '',
              '  static let byID: [String: APIOperation] = Dictionary(uniqueKeysWithValues: all.map { ($0.id, $0) })',
              '}', '']
    return '\n'.join(lines)


def client_source(spec_path, spec):
    lines = ['// Generated by scripts/generate_api_client.py. Do not edit.',
             '// OpenAPI SHA-256: ' + hashlib.sha256(spec_path.read_bytes()).hexdigest(),
             'import Foundation', '', 'extension APGIAPIClient {']
    assert set(spec['components']['schemas']['MetaResponse']['required']) == {
        'researcher', 'osf', 'zenodo', 'code', 'web', 'licences', 'release_state'}
    for name, path in (('metadata', '/v1/meta'), ('version', '/v1/version')):
        operation = spec['paths'][path]['get']
        lines += ['  /// ' + operation['operationId'],
                  f'  func {name}() async throws -> [String: APIJSONValue] {{',
                  f'    try await get("{path}")', '  }', '']
    lines += ['}', '']
    return '\n'.join(lines)


def outputs():
    v1_path, v1 = load('openapi-v1.json')
    research_path, research = load('explorer-research-v1.json')
    return {
        ROOT / 'APGI-Explorer/Core/APIOperationCatalog+Generated.swift': catalog_source(
            v1_path, v1, 'APGIOperations',
            'Every operation of the pinned deployed OpenAPI v1 contract.'),
        ROOT / 'APGI-Explorer/Core/ResearchOperationCatalog+Generated.swift': catalog_source(
            research_path, research, 'ExplorerResearchOperations',
            'Explorer research operations from the not-yet-deployed contract extract.'),
        ROOT / 'APGI-Explorer/Services/APGIAPIClient+Generated.swift': client_source(v1_path, v1),
    }


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for target, text in outputs().items():
        if args.check:
            assert target.read_text() == text, f'Regenerate {target.relative_to(ROOT)}'
        else:
            target.write_text(text)
    print('API catalog generation OK' if args.check else 'Generated API catalogs')
