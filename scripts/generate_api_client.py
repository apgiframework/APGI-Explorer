"""Generate the public Explorer API surface from the pinned deployed OpenAPI contract."""
import argparse
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / 'contracts/openapi-v1.json'
spec = json.loads(source.read_text())
operations = [('metadata', '/v1/meta'), ('version', '/v1/version')]
assert spec['openapi'].startswith('3.')
assert set(spec['components']['schemas']['MetaResponse']['required']) == {
    'researcher', 'osf', 'zenodo', 'code', 'web', 'licences', 'release_state'}
lines = ['// Generated by scripts/generate_api_client.py. Do not edit.',
         '// OpenAPI SHA-256: ' + hashlib.sha256(source.read_bytes()).hexdigest(),
         'import Foundation', '', 'extension APGIAPIClient {']
for name, path in operations:
    operation = spec['paths'][path]['get']
    assert not operation.get('security'), 'Public client must never require participant credentials'
    lines += ['  /// ' + operation['operationId'],
              f'  func {name}() async throws -> [String: APIJSONValue] {{',
              f'    try await get("{path}")', '  }', '']
lines += ['}', '']
output = '\n'.join(lines)
target = root / 'APGI-Explorer/Services/APGIAPIClient+Generated.swift'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    assert target.read_text() == output, 'Regenerate the Swift API client'
else:
    target.write_text(output)
