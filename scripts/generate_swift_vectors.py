"""Generate the cross-implementation upload vectors shared by Explorer and apgi-api.

The file holds canonical payload bytes, SHA-256 digests and deterministic event keys.
Explorer's portable Swift tests assert that the Swift implementation reproduces every
value byte for byte (HashingTests, UploadVectorTests); apgi-api's integration tests
replay the same events against the real routes (tests/integration/test_explorer_swift_vectors.py).
The same file is committed in both repositories and CI compares the two copies.

    python3 scripts/generate_swift_vectors.py          # rewrite
    python3 scripts/generate_swift_vectors.py --check  # CI
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / 'Tests/ExplorerCoreTests/Fixtures'
TARGET = FIXTURES / 'upload-vectors.json'
SESSION_ID = 'vector-session'


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(',', ':'), ensure_ascii=False)


def sha256_hex(text):
    return hashlib.sha256(text.encode('utf-8')).hexdigest()


def event_key(session_id, seq_no):
    """Mirror of EventKey.make in APGI-Explorer/Core/ResearchOutbox.swift."""
    raw = bytearray(hashlib.sha256(f'apgi-explorer-event:{session_id}:{seq_no}'.encode()).digest()[:16])
    raw[6] = (raw[6] & 0x0F) | 0x50
    raw[8] = (raw[8] & 0x3F) | 0x80
    h = raw.hex()
    return '-'.join([h[0:8], h[8:12], h[12:16], h[16:20], h[20:32]])


def event(bank_sha, seq):
    payload = {'item_id': seq + 1, 'value': 1 + seq % 4, 'latency_us': 1_500_000 + seq, 'instrument_sha256': bank_sha}
    if seq % 5 == 4:
        payload['previous_value'] = 1 + (seq + 1) % 4
    text = canonical(payload)
    return {'event_id': event_key(SESSION_ID, seq), 'seq_no': seq, 'payload': payload,
            'canonical': text, 'payload_sha256': sha256_hex(text)}


def build():
    pin = json.loads((ROOT / 'contracts/explorer-instrument-pin.json').read_text())
    bank_sha = pin['sha256']
    events = [event(bank_sha, seq) for seq in range(35)]
    changed = dict(events[0]['payload'], value=4)
    conflict = {'event_id': events[0]['event_id'], 'seq_no': 0, 'payload': changed,
                'canonical': canonical(changed), 'payload_sha256': sha256_hex(canonical(changed))}
    return {
        'description': 'Swift-verified canonical payloads for Explorer research uploads. Generated by '
                       'scripts/generate_swift_vectors.py; do not edit.',
        'session_id': SESSION_ID,
        'instrument_sha256': bank_sha,
        'canonical_vectors': json.loads((FIXTURES / 'canonical-vectors.json').read_text()),
        'events': events,
        'conflicting_event_for_seq_0': conflict,
    }


def render():
    return json.dumps(build(), indent=1, ensure_ascii=False, sort_keys=True) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if args.check:
        assert TARGET.read_text() == render(), 'Regenerate Tests/ExplorerCoreTests/Fixtures/upload-vectors.json'
        print('upload vectors OK')
    else:
        TARGET.write_text(render())
        print('wrote', TARGET.relative_to(ROOT))
