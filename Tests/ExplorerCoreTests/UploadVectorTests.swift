import XCTest
@testable import ExplorerCore

/// Captures upload requests and acknowledges every event, standing in for the transport only.
final class CapturingSender: OperationSending, @unchecked Sendable {
  private let lock = NSLock()
  private var captured: [APIJSONValue] = []
  var requestBodies: [APIJSONValue] { lock.withLock { captured } }

  func send(_ operation: APIOperation, request: APIRequest, authentication: APIAuthentication) async throws -> APIJSONValue {
    lock.withLock { captured.append(request.body ?? .null) }
    let events = request.body?.object?["events"]?.array ?? []
    return .object(["acks": .array(events.compactMap { event in
      guard let fields = event.object else { return nil }
      return .object([
        "event_id": fields["event_id"] ?? .null, "seq_no": fields["seq_no"] ?? .null,
        "payload_sha256": fields["payload_sha256"] ?? .null,
        "status": .string("accepted"), "server_verified": .bool(true)])
    })])
  }
}

/// `Fixtures/upload-vectors.json` is generated by `scripts/generate_swift_vectors.py` and is committed
/// byte-identically in apgi-api, whose integration tests replay it against the real routes
/// (`tests/integration/test_explorer_swift_vectors.py`). These tests prove that Swift produces
/// exactly the keys, canonical bytes, digests and wire bodies the server tests consume.
final class UploadVectorTests: XCTestCase {
  private func vectors() throws -> [String: APIJSONValue] { try XCTUnwrap(Fixture.json("upload-vectors").object) }

  func testPinnedBankHashMatchesTheVectors() throws {
    XCTAssertEqual(try vectors()["instrument_sha256"]?.string, ResearchPins.bankSHA256)
  }

  func testSwiftReproducesEveryKeyCanonicalPayloadAndDigest() throws {
    let file = try vectors()
    let sessionID = try XCTUnwrap(file["session_id"]?.string)
    let events = try XCTUnwrap(file["events"]?.array)
    XCTAssertEqual(events.count, 35)
    for event in events {
      let fields = try XCTUnwrap(event.object)
      let seq = try XCTUnwrap(fields["seq_no"]?.int)
      let payload = try XCTUnwrap(fields["payload"])
      let bytes = try CanonicalJSON.bytes(payload)
      XCTAssertEqual(String(decoding: bytes, as: UTF8.self), fields["canonical"]?.string, "seq \(seq)")
      XCTAssertEqual(PortableSHA256.hexDigest(bytes), fields["payload_sha256"]?.string, "seq \(seq)")
      XCTAssertEqual(EventKey.make(sessionID: sessionID, seqNo: seq), fields["event_id"]?.string, "seq \(seq)")
    }
    let conflict = try XCTUnwrap(file["conflicting_event_for_seq_0"]?.object)
    XCTAssertEqual(try CanonicalJSON.sha256Hex(try XCTUnwrap(conflict["payload"])), conflict["payload_sha256"]?.string)
    XCTAssertEqual(conflict["event_id"], events.first?.object?["event_id"], "the conflict reuses seq 0 and its key")
    XCTAssertNotEqual(conflict["payload_sha256"], events.first?.object?["payload_sha256"])
  }

  func testCoordinatorSendsExactlyTheVectorWireBody() async throws {
    let file = try vectors()
    let sessionID = try XCTUnwrap(file["session_id"]?.string)
    let events = try XCTUnwrap(file["events"]?.array)
    let sender = CapturingSender()
    let coordinator = UploadCoordinator(
      store: InMemoryPendingEventStore(), adapter: ExplorerResearchAdapter(transport: sender),
      capability: ResearchCapability(isEnabled: true), authorization: { "token" })
    for event in events {
      let fields = try XCTUnwrap(event.object)
      _ = try await coordinator.enqueue(sessionID: sessionID, seqNo: try XCTUnwrap(fields["seq_no"]?.int),
                                        payload: try XCTUnwrap(fields["payload"]))
    }
    let result = await coordinator.drain(sessionID: sessionID)
    XCTAssertEqual(result.verified, 35)
    let sent = try XCTUnwrap(sender.requestBodies.first?.object?["events"]?.array)
    let expected: [APIJSONValue] = try events.map { event in
      let fields = try XCTUnwrap(event.object)
      return .object(["event_id": try XCTUnwrap(fields["event_id"]), "seq_no": try XCTUnwrap(fields["seq_no"]),
                      "payload": try XCTUnwrap(fields["payload"]), "payload_sha256": try XCTUnwrap(fields["payload_sha256"])])
    }
    XCTAssertEqual(sent, expected)
  }
}
